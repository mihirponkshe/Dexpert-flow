/**
 * Extract unique tenants from shipment data.
 */
export function getTenantsFromShipments(shipments: Shipment[]): { id: string; name: string }[] {
  const map = new Map<string, string>();
  for (const s of shipments) {
    if (!map.has(s.tenantId)) {
      map.set(s.tenantId, s.tenantName);
    }
  }
  return Array.from(map.entries()).map(([id, name]) => ({ id, name }));
}
